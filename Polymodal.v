  pose proof (prov_weaken _ (Box n phi) HFnphi) as Hbwd.
  pose proof (prov_weaken _ (F n phi) HBoxnphi) as Hfwd.
  exact (prov_and_intro_meta _ _ Hfwd Hbwd).
